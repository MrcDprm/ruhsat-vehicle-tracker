export const MAKES = Object.keys(CATALOG).sort((a, b) => a.localeCompare(b, 'tr'));

// Birleşik aksan işaretleri (U+0300-U+036F): NFD ayrıştırmasından sonra "ë" → "e" + işaret.
const COMBINING_MARKS = new RegExp(`[${String.fromCharCode(0x300)}-${String.fromCharCode(0x36f)}]`, 'g');

/** Karşılaştırma anahtarı: küçük harf, ı/i, aksan, boşluk ve tire farkı yok ("CITROEN", "cıtroen", "Citroën"; "crv", "CR-V"). */
export function fold(s: string): string {
  return s
    .trim()
    .toLocaleLowerCase('tr-TR')
    .replace(/ı/g, 'i')
    .normalize('NFD')
    .replace(COMBINING_MARKS, '')
    .replace(/[\s\-.]+/g, '');
}

function suggest(options: string[], query: string, limit: number): string[] {
  const q = fold(query);
  if (q === '') return [];
  if (options.some((o) => fold(o) === q)) return [];
  return options.filter((o) => fold(o).startsWith(q)).slice(0, limit);
}

/** Yazılana göre marka önerileri; tam eşleşmede öneri yok (zaten doğru yazılmış ya da kayıtta düzeltilecek). */
export function suggestMakes(query: string, limit = 6): string[] {
  return suggest(MAKES, query, limit);
}

/** Markaya göre model önerileri. Marka katalogda yoksa öneri yok. Boş sorguda markanın ilk modelleri. */
export function suggestModels(make: string, query: string, limit = 8): string[] {
  const known = canonicalMake(make);
  const models = known ? CATALOG[known] : [];
  if (query.trim() === '') return models.slice(0, limit);
  return suggest(models, query, limit);
}

// Halkın kısaca yazdığı adlar.
const ALIASES: Record<string, string> = {
  mercedes: 'Mercedes-Benz',
  benz: 'Mercedes-Benz',
  vw: 'Volkswagen',
  alfa: 'Alfa Romeo',
  ssangyong: 'KGM',
  landrover: 'Land Rover',
};

/** Katalogdaki yazım: "ford" → "Ford", "mg" → "MG", "mercedes" → "Mercedes-Benz". Bilinmiyorsa null. */
export function canonicalMake(raw: string): string | null {
  const q = fold(raw);
  if (q === '') return null;
  return MAKES.find((m) => fold(m) === q) ?? ALIASES[q] ?? null;
}

export function canonicalModel(make: string, raw: string): string | null {
  const known = canonicalMake(make);
  if (!known) return null;
  const q = fold(raw);
  return CATALOG[known].find((m) => fold(m) === q) ?? null;
}

/** Katalogda olmayan ve tamamen küçük harfle yazılmış adın kelime başları büyütülür ("anadol" → "Anadol"). */
export function tidyName(raw: string): string {
  const s = raw.trim().replace(/\s+/g, ' ');
  if (s !== s.toLocaleLowerCase('tr-TR')) return s;
  return s.replace(/(^|\s)(\S)/g, (_, sp: string, ch: string) => sp + ch.toLocaleUpperCase('tr-TR'));
}
